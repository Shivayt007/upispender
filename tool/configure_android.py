"""Prepare generated Android Gradle configuration for scheduled notifications.

Android platform is generated by flutter create in CI. Do not embed credentials.
"""
from pathlib import Path

gradle = Path("android/app/build.gradle.kts")
if not gradle.exists():
    raise SystemExit("Missing generated android/app/build.gradle.kts")
code = gradle.read_text()
if "isCoreLibraryDesugaringEnabled = true" not in code:
    code = code.replace(
        "compileOptions {",
        "compileOptions {\n        isCoreLibraryDesugaringEnabled = true",
        1,
    )
if "coreLibraryDesugaring(" not in code:
    code += '\n\ndependencies {\n    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")\n}\n'
gradle.write_text(code)
print("Configured Android core library desugaring")
